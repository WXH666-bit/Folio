import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { isolatedEnv, snapshotPiConfig, balancedJobs } from "./ab/isolation.mjs";
import { guardInput } from "./ab/pi-isolation-guard.mjs";
const dir = fs.mkdtempSync(path.resolve("tests/tmp/isolation-"));
const personal = path.join(dir, "personal", ".pi");
fs.mkdirSync(path.join(personal,"agent"), {recursive:true});
fs.writeFileSync(path.join(personal,"agent","settings.json"), '{"test":true}');
const before = snapshotPiConfig(personal);
const inherited = { HOME: "/personal", USERPROFILE: "/personal", PI_CODING_AGENT_DIR: "/personal/.pi/agent", PI_EXTRA_CONFIG: "/personal/extra", PATH: process.env.PATH, AIGW_API_KEY: "example-placeholder" };
const isolated = path.join(dir,"run");
const env = isolatedEnv(isolated,path.join(isolated,"agent"),inherited);
for(const key of ["HOME","USERPROFILE","APPDATA","LOCALAPPDATA","TEMP","TMP","TMPDIR","XDG_CONFIG_HOME","XDG_CACHE_HOME","XDG_DATA_HOME","NPM_CONFIG_USERCONFIG","NPM_CONFIG_GLOBALCONFIG"]) assert.ok(env[key].startsWith(isolated),key);
assert.equal(env.PI_EXTRA_CONFIG,undefined);
assert.equal(env.AIGW_API_KEY,"example-placeholder");
assert.equal(inherited.HOME,"/personal");
assert.deepEqual(snapshotPiConfig(personal),before);
fs.writeFileSync(path.join(personal,"agent","settings.json"), '{}');
assert.notDeepEqual(snapshotPiConfig(personal),before);
const jobs = balancedJobs(["A","B"],[{id:"one"},{id:"two"}],3);
assert.equal(jobs.length,12);
for(let i=0;i<jobs.length;i+=2){assert.equal(jobs[i].q.id,jobs[i+1].q.id);assert.equal(jobs[i].r,jobs[i+1].r);assert.notEqual(jobs[i].arm,jobs[i+1].arm);}
assert.equal(jobs.filter(j=>j.arm==="A").length,6);
const work=path.join(isolated,"work"),temp=path.join(isolated,"temp");
const event={toolName:"bash",input:{command:"python -c \"open('/tmp/out.txt','w')\"; cat /tmp/out.txt"}};
assert.equal(guardInput(event,isolated,work,temp).changed,true);
assert.ok(event.input.command.includes(temp.replace(/\\/g,"/")));
assert.ok(!event.input.command.includes("'/tmp/"));
const local={toolName:"bash",input:{command:"cat ./tests/tmp/out.txt"}};
assert.equal(guardInput(local,isolated,work,temp).changed,false);
assert.equal(guardInput({toolName:"bash",input:{command:"cat C:/Users/person/.pi/agent/settings.json"}},isolated,work,temp).block,true);
assert.equal(guardInput({toolName:"write",input:{path:path.resolve(dir,"outside.txt")}},isolated,work,temp).block,true);
const redirected={toolName:"read",input:{path:"/tmp/out.txt"}};
assert.equal(guardInput(redirected,isolated,work,temp).changed,true);
console.log("OK — isolated pi environment, personal-config fingerprints and paired scheduling");
